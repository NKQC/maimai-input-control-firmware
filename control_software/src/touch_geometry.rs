/// 射线法 point-in-polygon: (px,py) 是否在 poly 内(边界视为命中)。
fn _point_in_polygon(px: f32, py: f32, poly: &[[f32; 2]]) -> bool {
    let n = poly.len();
    if n < 3 {
        return false;
    }
    let mut inside = false;
    let mut j = n - 1;
    for i in 0..n {
        let (xi, yi) = (poly[i][0], poly[i][1]);
        let (xj, yj) = (poly[j][0], poly[j][1]);
        if (yi > py) != (yj > py) {
            let x_at_y = xi + (py - yi) / (yj - yi) * (xj - xi);
            if px < x_at_y {
                inside = !inside;
            }
        }
        j = i;
    }
    inside
}

/// 精确命中检测: (x,y) 为 [`SCREEN_W`]x[`SCREEN_H`] 坐标系下的一点,
/// 返回命中的分区 index(0..33), 未命中返回 `None`。bbox 预筛 + 逐区
/// point-in-polygon, 取代旧的 34 个重叠 bbox TouchArea 命中层。
pub fn hit_test(x: f32, y: f32) -> Option<usize> {
    for i in 0..34usize {
        let g = &ZONE_GEOMETRY[i];
        if x < g.min_x || x > g.min_x + g.width || y < g.min_y || y > g.min_y + g.height {
            continue;
        }
        if _point_in_polygon(x, y, ZONE_HIT_POINTS[i]) {
            return Some(i);
        }
    }
    None
}
