/// 单个逻辑分区(0..33)的静态几何: SVG path(M/L/A/Z) + 局部包围盒 + 标签点,
/// 全部分区几何并集的紧包围盒 (min_x, min_y, width, height)。
/// 触控为圆形布局, 在 16:9 视框里四周有大量留白; UI 用本 bbox 作绘制视框,
/// 使分区图铺满画布而非缩在中间。命中检测仍在 SCREEN 坐标系。
pub fn content_bbox() -> (f32, f32, f32, f32) {
    let mut min_x = f32::INFINITY;
    let mut min_y = f32::INFINITY;
    let mut max_x = f32::NEG_INFINITY;
    let mut max_y = f32::NEG_INFINITY;
    for g in ZONE_GEOMETRY.iter() {
        min_x = min_x.min(g.min_x);
        min_y = min_y.min(g.min_y);
        max_x = max_x.max(g.min_x + g.width);
        max_y = max_y.max(g.min_y + g.height);
    }
    (min_x, min_y, max_x - min_x, max_y - min_y)
}

